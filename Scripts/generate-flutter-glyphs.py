#!/usr/bin/env python3
"""Translate the canonical generated brand paths to Flutter's Path API."""

from pathlib import Path
import argparse
import re


parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
arguments = parser.parse_args()
root = Path(__file__).resolve().parents[1]
source = (root / 'Sources/InboxPlusUI/PlatformGlyphPaths.swift').read_text()
aliases = {'whatsApp': 'whatsapp', 'facebookMessenger': 'messenger', 'iMessage': 'imessage'}
lines = ["// Generated by Scripts/generate-flutter-glyphs.py; do not edit.",
         "// Simple Icons brand marks are CC0; trademarks belong to their owners.",
         "import 'dart:ui';", "", "Path? platformGlyphPath(String platform) {", "  switch (platform) {"]
for name, body in re.findall(r'case \.(\w+):\s*var path = Path\(\)(.*?)return path', source, re.S):
    lines.extend([f"    case '{aliases.get(name, name)}':", "      return Path()"])
    for command in body.splitlines():
        values = re.findall(r'-?\d+\.\d+', command)
        if 'path.move' in command:
            method, args = 'moveTo', values
        elif 'path.addLine' in command:
            method, args = 'lineTo', values
        elif 'path.addCurve' in command:
            method, args = 'cubicTo', values[2:] + values[:2]
        elif 'path.addQuadCurve' in command:
            method, args = 'quadraticBezierTo', values[2:] + values[:2]
        elif 'path.closeSubpath' in command:
            method, args = 'close', []
        else:
            continue
        lines.append(f"        ..{method}({', '.join(args)})")
    lines[-1] += ';'
lines.extend(["    default:", "      return null;", "  }", "}", ""])
destination = root / 'apps/inboxplus_flutter/lib/ui/platform_glyphs.dart'
generated = '\n'.join(lines)
if arguments.check:
    if destination.read_text() != generated:
        raise SystemExit('Flutter platform glyphs differ; run Scripts/generate-flutter-glyphs.py.')
else:
    destination.write_text(generated)
